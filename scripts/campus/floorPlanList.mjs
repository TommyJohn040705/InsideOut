// Writes the floor-plan checklist: every Plant Operations floor plan, grouped by building,
// with its link, restriction and mapping status.
// Run: node scripts/campus/floorPlanList.mjs -> docs/FLOOR_PLANS.md, docs/floor-plans.csv
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const buildings = JSON.parse(readFileSync('src/data/campus/buildings.json', 'utf8'));
const pdfDir = 'data-sources/plantops/pdfs';
const MAPPED = { E5: ['01', '02', '03', '04', '05', '06'] }; // traced drawings in the app (src/campus/campusData.ts INDOOR)
const order = (c) => (/^B(\d)$/.test(c) ? -Number(c.slice(1)) : /^\d+$/.test(c) ? Number(c) : { CON: 1.4, MEZ: 1.5, PH: 90, RO: 99 }[c] ?? 50);
const status = (b, f) => MAPPED[b.id]?.includes(f.floorCode) ? 'Mapped (draft alignment)' : existsSync(`${pdfDir}/${f.filename}`) ? 'PDF saved, not imported' : 'Needed';
const label = (b) => `${b.code || b.id}${b.name ? ` – ${b.name}` : ''}`;

const withPlans = buildings.filter((b) => b.floors.length).sort((a, z) => (a.code || a.id).localeCompare(z.code || z.id));
const onMap = withPlans.filter((b) => b.footprint), offMap = withPlans.filter((b) => !b.footprint);
// Village 1 drawing sets are listed under every house they cover; count each document once.
const uniq = (fl) => [...new Map(fl.map((f) => [f.filename, f])).values()];
const all = uniq(withPlans.flatMap((b) => b.floors));
const noPlans = buildings.filter((b) => b.footprint && !b.floors.length).sort((a, z) => (a.code || a.name || a.id).localeCompare(z.code || z.name || z.id));
const n = (bs) => uniq(bs.flatMap((b) => b.floors)).length, r = (bs) => uniq(bs.flatMap((b) => b.floors)).filter((f) => f.restricted).length;

const csv = [['on_campus_map', 'building', 'name', 'floor', 'filename', 'restricted', 'status', 'url']];
const section = (bs, on) => bs.map((b) => {
  const fl = [...b.floors].sort((a, z) => order(a.floorCode) - order(z.floorCode));
  for (const f of fl) csv.push([on ? 'yes' : 'no', b.code || b.id, b.name || '', f.floorCode, f.filename, f.restricted ? 'yes' : 'no', status(b, f), f.url]);
  return `### ${label(b)}\n\n${fl.length} plans${fl.some((f) => f.restricted) ? `, ${fl.filter((f) => f.restricted).length} restricted` : ''}.\n\n| Floor | File | Restricted | Status |\n|---|---|---|---|\n` +
    fl.map((f) => `| ${f.floorCode} | [${f.filename}](${f.url}) | ${f.restricted ? 'yes' : ''} | ${status(b, f)} |`).join('\n') + '\n';
}).join('\n');

const md = `# Floor plans needed for InsideOut

Generated by \`node scripts/campus/floorPlanList.mjs\` from the Plant Operations floor-plan list (via Wayfinder) on ${new Date().toISOString().slice(0, 10)}. A spreadsheet version is in [floor-plans.csv](floor-plans.csv).

## Summary

| | Buildings | Floor plans | Restricted |
|---|---|---|---|
| On the campus map, plans listed | ${onMap.length} | ${n(onMap)} | ${r(onMap)} |
| On the campus map, no plans listed | ${noPlans.length} | 0 | 0 |
| Listed but not on the map (no footprint matched) | ${offMap.length} | ${n(offMap)} | ${r(offMap)} |
| **Total with plans** | **${withPlans.length}** | **${all.length}** | **${all.filter((f) => f.restricted).length}** |

Mapped so far: E5 floors 1–6 only. Every other plan is still needed. (The source list has 491 entries; MC floors 5 and 6 appear twice, so there are 489 distinct plans.)

## How to get them

- Every link goes to \`plantops.uwaterloo.ca\` and asks for a **UW login** (checked 2026-11-12). Someone with a UW account has to download them; the app cannot.
- **Restricted** plans need permission from Plant Operations before use. Ask before downloading or importing them.
- Save PDFs with their original filenames in \`data-sources/plantops/pdfs/\` (never committed), then re-run this script to see them marked "PDF saved". Import each one in the app: campus map → **Floor plans**.
- Floor codes: B1 basement, MEZ mezzanine, CON concourse, PH penthouse, RO roof. Roof and penthouse plans are rarely needed for navigation.

## On the campus map

${section(onMap, true)}
## Listed but not on the map

These codes have plans but no building footprint matched in OpenStreetMap (many are residences or off the main campus).

${section(offMap, false)}
## On the map but no floor plans listed

These buildings are drawn on the campus map but have no Plant Operations floor plan in the list. Indoor maps for them need another source (ask Plant Operations, or use OpenStreetMap indoor data where it exists).

| Building | Name | Rooms surveyed in OpenStreetMap |
|---|---|---|
${noPlans.map((b) => `| ${b.code || '–'} | ${b.name || b.id} | ${b.osmIndoor.reduce((s, l) => s + l.rooms, 0) || ''} |`).join('\n')}
`;

writeFileSync('docs/FLOOR_PLANS.md', md);
writeFileSync('docs/floor-plans.csv', csv.map((row) => row.map((v) => (/[",\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v)).join(',')).join('\n') + '\n');
console.log(`${withPlans.length} buildings, ${all.length} plans (${onMap.length} buildings / ${n(onMap)} plans on the map)`);

// Clickable download page: open it in a browser signed in to UW and click through the list.
const esc = (s) => String(s).replace(/[&<>"]/g, (ch) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[ch]);
const seen = new Set();
const groups = onMap.map((b) => {
  const fl = [...b.floors].sort((a, z) => order(a.floorCode) - order(z.floorCode)).filter((f) => !seen.has(f.filename) && seen.add(f.filename));
  if (!fl.length) return '';
  return `<h2>${esc(label(b))}</h2><ul>${fl.map((f) => `<li><label><input type="checkbox"> <a href="${esc(f.url)}" download>${esc(f.filename)}</a></label> ${f.wing ? `<span class="w">${esc(f.wing)}</span>` : ''}${f.restricted ? '<span class="r">restricted: needs Plant Operations permission</span>' : ''}${status(b, f) !== 'Needed' ? `<span class="d">${esc(status(b, f))}</span>` : ''}</li>`).join('')}</ul>`;
}).join('\n');
writeFileSync('docs/floor-plan-downloads.html', `<!doctype html><meta charset="utf-8"><title>UW floor plans to download</title>
<style>body{font:14px system-ui,sans-serif;max-width:860px;margin:24px auto;padding:0 16px;color:#1e293b}h2{font-size:15px;margin:18px 0 4px}ul{margin:0;padding-left:4px;list-style:none}li{padding:2px 0}a{color:#1d4ed8}.r{color:#9f1239;margin-left:8px;font-size:12px}.w{background:#e2e8f0;border-radius:4px;padding:0 4px;margin-left:6px;font-size:12px}.d{color:#047857;margin-left:8px;font-size:12px}.box{background:#fef3c7;border-radius:8px;padding:10px 12px}</style>
<h1>UW floor plans to download for InsideOut</h1>
<div class="box">Sign in to plantops.uwaterloo.ca in this browser first (UW login). Then click each link to download it. Tick the box as you go.<br>
Skip the <b>restricted</b> ones unless Plant Operations has given permission.<br>
When done, put the PDFs (keep their names) in <code>data-sources/plantops/pdfs/</code> of the InsideOut folder, or add them in the app: campus map → Floor plans → Bulk import.</div>
<p>${onMap.length} buildings on the campus map · ${n(onMap)} documents (${n(onMap) - r(onMap)} not restricted, ${r(onMap)} restricted). Generated ${new Date().toISOString().slice(0, 10)}.</p>
${groups}
`);
